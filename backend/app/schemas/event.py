    LEAD_CONTACTED = "LEAD_CONTACTED"
    LEAD_NOT_CONTACTED = "LEAD_NOT_CONTACTED"
    CALL_COMPLETED = "CALL_COMPLETED"
    MEETING_COMPLETED = "MEETING_COMPLETED"
    ACTION_COMPLETED = "ACTION_COMPLETED"
    ACTION_SNOOZED = "ACTION_SNOOZED"
    ACTION_REASSIGNED = "ACTION_REASSIGNED"
    ACTION_OUTCOME_RECORDED = "ACTION_OUTCOME_RECORDED"
    FOLLOWUP_CREATED = "FOLLOWUP_CREATED"
    FOLLOWUP_COMPLETED = "FOLLOWUP_COMPLETED"
    PAYIN_RECEIVED = "PAYIN_RECEIVED"
    PRODUCT_PURCHASED = "PRODUCT_PURCHASED"
    ORDER_COMPLETED = "ORDER_COMPLETED"
    REDEMPTION = "REDEMPTION"
    CUSTOMER_BECAME_ACTIVE = "CUSTOMER_BECAME_ACTIVE"
    WEBSITE_VISIT = "WEBSITE_VISIT"
    PRODUCT_ENQUIRY = "PRODUCT_ENQUIRY"
    CAMPAIGN_RESPONSE = "CAMPAIGN_RESPONSE"
    CONVERSION_COMPLETED = "CONVERSION_COMPLETED"
    TARGET_UPDATED = "TARGET_UPDATED"
    SLA_UPDATED = "SLA_UPDATED"
    BENCHMARK_UPDATED = "BENCHMARK_UPDATED"
    PRODUCT_VIEW = "PRODUCT_VIEW"
    CART_CREATED = "CART_CREATED"
    CHECKOUT_STARTED = "CHECKOUT_STARTED"
    PURCHASE = "PURCHASE"
    LOGIN = "LOGIN"
    LOW_USAGE = "LOW_USAGE"
    SUPPORT_TICKET = "SUPPORT_TICKET"
    NEGATIVE_FEEDBACK = "NEGATIVE_FEEDBACK"
    SUPPORT_INTERACTION = "SUPPORT_INTERACTION"
    SECOND_PURCHASE = "SECOND_PURCHASE"
    APPLICATION_STARTED = "APPLICATION_STARTED"
    APPLICATION_COMPLETED = "APPLICATION_COMPLETED"
    PURCHASE_INTENT = "PURCHASE_INTENT"
    UPSELL_SIGNAL = "UPSELL_SIGNAL"
    CROSS_SELL_SIGNAL = "CROSS_SELL_SIGNAL"
